def turbulence_initial_values(model: Model) -> tuple[float, float]:
    """Initial k and epsilon for the whole POD.

    The velocity scale is buoyant rather than the supply face velocity, and
    epsilon is derived from k so the pair keeps a room-scale length. Flooring
    epsilon on its own collapses the turbulent viscosity to roughly molecular
    and leaves a steady solver chasing vortices a real room would damp -- see
    aicfd.case.turbulence_initial_values for the full account.
    """
    buoyant = math.sqrt(
        9.81
        * max(min(model.design_delta_t_k, 30.0), 1.0)
        / T_REFERENCE_K
        * model.domain.size[2]
    )
    characteristic = max(model.fan_face_velocity_ms, buoyant)
    k = max(1.5 * (characteristic * TURBULENCE_INTENSITY) ** 2, 1e-6)
    length_scale = LENGTH_SCALE_FRACTION * model.domain.size[2]
    return k, C_MU**0.75 * k**1.5 / length_scale


