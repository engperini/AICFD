def _plenum_lines(model: Model) -> list[str]:
    """What the wall between the hall and the gallery is, in the summary.

    Three arrangements, and the summary has to say which one this is: a
    single wall, a double wall with grilles in its inner leaf, or a double
    wall whose inner leaf is mesh. The last two share their geometry and
    differ in what the leaf is and in whether the building grew for it
    (ADR-058, ADR-060).
    """
    if not model.plenum_depth or not model.plenum_grilles:
        return []
    face = sum(g.area for g in model.plenum_grilles)
    if model.supply_mesh_k is not None:
        return [
            f"  Supply plenum   {model.plenum_depth:g} m deep, closed on the "
            f"hall side by 13 x 13 mm mesh over {face:.1f} m2; the hall keeps "
            f"the size it was built at",
            f"  Supply mesh     {model.plenum_face_velocity_ms:.2f} m/s "
            f"through it, {model.plenum_pressure_drop_pa or 0.0:.2f} Pa",
        ]
    return [
        f"  Supply plenum   {model.plenum_depth:g} m between the two leaves "
        f"of the hall wall, {len(model.plenum_grilles)} grille(s), "
        f"{face:.1f} m2 of face",
        f"  Supply grilles  {model.plenum_face_velocity_ms:.2f} m/s on the "
        f"face, {model.plenum_pressure_drop_pa or 0.0:.2f} Pa",
    ]


def _unit_label(model: Model) -> str:
    """What the summary calls this room's machines, pluralised where there is
    more than one: `Fan walls`, `CRACs`, `CRAHs` (ADR-102)."""
    naming = unit_naming(model.equipment, model.floor_height)
    word = naming["plural"] if model.fan_count > 1 else naming["noun"]
    return word[0].upper() + word[1:]


def summary(model: Model) -> str:
    """What the generator derived, in the user's units."""
    dx, dy, dz = model.domain.size
    k, epsilon = turbulence_initial_values(model)
    lines = [
        f"Case '{model.name}'",
        f"  Domain          {dx:g} x {dy:g} x {dz:g} m",
        f"  Mesh            {'x'.join(str(n) for n in model.divisions)} "
        f"= {model.n_cells:,} cells ("
        + " x ".join(f"{c:.2f}" for c in model.cell_size)
        + " m)",
        f"  IT load         {model.total_load_w / 1000:.1f} kW across "
        f"{len(model.racks)} rack(s)",
        # Named for what the room really has: a wall of fans, or the CRACs
        # and CRAHs that stand in it. The column stays put either way
        # (ADR-102).
        f"  {_unit_label(model):<15} "
        + (f"{model.fan_count} x " if model.fan_count > 1 else "")
        + f"{model.unit_airflow_m3h:,.0f} m3/h at "
        f"{model.supply_temp_c:.1f} degC, "
        f"{model.fan_face_velocity_ms:.2f} m/s through "
        f"{model.fans[0].area:.2f} m2" + (" each" if model.fan_count > 1 else ""),
        f"  Rack demand     {model.rack_demand_m3s * 3600:,.0f} m3/h "
        f"({model.rack_demand_m3s * 3600 / model.airflow_m3h * 100:.0f}% of supply)",
        f"  Design bulk dT  {model.design_delta_t_k:.1f} K",
        *_plenum_lines(model),
        f"  Site air        {model.altitude_m:.0f} m, {model.pressure_pa / 1000:.1f} kPa, "
        f"rho {model.rho:.3f} kg/m3",
        *_hvac_lines(model),
        f"  Turbulence      k {k:.4g} m2/s2, epsilon {epsilon:.4g} m2/s3",
        "",
        "  Internal surfaces built by createBaffles:",
    ]
    for name, panels, holes in wall_plan(model):
        holed = f", less {len(holes)} opening(s)" if holes else ""
        area = sum(p.area for p in panels)
        where = (
            f"at {panels[0].position:g} m"
            if len(panels) == 1
            else f"{len(panels)} panels"
        )
        lines.append(
            f"    {name:<22} normal {'xyz'[panels[0].axis]} {where}, "
            f"{area:.2f} m2{holed}"
        )
    # A porous surface that is not a hole in any wall has no zone in the plan
    # above, and this list is read as what createBaffles builds -- so the mesh
    # leaf, which is a surface all by itself, was built and not listed
    # (ADR-060).
    holes = {h.name for _z, _w, hs in wall_plan(model) for h in hs}
    for panel in porous(model):
        if panel.name in holes:
            continue
        lines.append(
            f"    {panel.name:<22} normal {'xyz'[panel.axis]} at "
            f"{panel.position:g} m, {panel.area:.2f} m2, "
            f"K {panel.resistance:.2f}"
        )
    for fan, (intake, supply) in zip(model.fans, fan_patches(model)):
        # A FAN WALL AND A DOWNFLOW UNIT ARE NOT THE SAME SHAPE, and this line
        # said "normal x ... y" for both. On a raised floor it printed the
        # x range of a z-normal face under the label y, so five units that
        # were correctly spread down two galleries read as three stacked in
        # one place and two in another -- a reader checking the placement was
        # shown a room that did not exist (ADR-097).
        label = fan.name + " (" + intake + "/" + supply + ")"
        (a0, a1), (b0, b1) = fan.extent
        if fan.return_z is not None:
            where = (f"horizontal, supplies at {fan.position:g} m and returns "
                     f"at {fan.return_z:g} m, x {a0:g}-{a1:g} y {b0:g}-{b1:g}")
        else:
            where = f"normal x at {fan.position:g} m, y {a0:g}-{a1:g}"
        lines.append(f"    {label:<22} {where}, {fan.area:.2f} m2")
    return "\n".join(lines) + "\n"
